package handler

import (
	"encoding/json"
	"testing"

	"omnirack-replica/backend/internal/service"
)

func TestRoomWriteRequestTracksRacksPerRowPresence(t *testing.T) {
	t.Run("omitted", func(t *testing.T) {
		var request roomWriteRequest
		if err := json.Unmarshal([]byte(`{"code":"ROOM-01","name":"一号机房"}`), &request); err != nil {
			t.Fatalf("unmarshal request: %v", err)
		}
		if request.Code != "ROOM-01" || request.Name != "一号机房" {
			t.Fatalf("embedded room fields were not decoded: %+v", request.Room)
		}
		if request.RacksPerRow.set {
			t.Fatal("omitted racksPerRow must remain unset")
		}
		if request.serviceInput().RacksPerRow != nil {
			t.Fatal("omitted racksPerRow must be passed to the service as nil")
		}
	})

	t.Run("explicit zero", func(t *testing.T) {
		var request roomWriteRequest
		if err := json.Unmarshal([]byte(`{"code":"ROOM-01","name":"一号机房","racksPerRow":0}`), &request); err != nil {
			t.Fatalf("unmarshal request: %v", err)
		}
		if !request.RacksPerRow.set || request.RacksPerRow.value != 0 {
			t.Fatalf("explicit zero presence was lost: %+v", request.RacksPerRow)
		}
		input := request.serviceInput()
		if input.RacksPerRow == nil || *input.RacksPerRow != 0 {
			t.Fatalf("explicit zero was not passed to the service: %v", input.RacksPerRow)
		}
	})

	t.Run("explicit null", func(t *testing.T) {
		var request roomWriteRequest
		if err := json.Unmarshal([]byte(`{"code":"ROOM-01","name":"一号机房","racksPerRow":null}`), &request); err == nil {
			t.Fatal("explicit null must be rejected")
		}
	})
}

func TestRackCreateRequestTracksTemplateSpecOverride(t *testing.T) {
	var request rackCreateRequest
	if err := json.Unmarshal([]byte(`{"code":"RACK-01","name":"一号机柜","autoGenerateCode":true,"overrideTemplateSpec":true,"widthMm":900,"depthMm":1300,"heightMm":2300}`), &request); err != nil {
		t.Fatalf("unmarshal request: %v", err)
	}
	if !request.AutoGenerateCode || !request.OverrideTemplateSpec {
		t.Fatalf("create-only options were lost: %+v", request)
	}
	if request.WidthMm != 900 || request.DepthMm != 1300 || request.HeightMm != 2300 {
		t.Fatalf("rack dimensions were not decoded: %+v", request.Rack)
	}
}

func TestRackTemplateCreateInputTracksAutoGeneratedCode(t *testing.T) {
	var input service.RackTemplateCreateInput
	if err := json.Unmarshal([]byte(`{"name":"自动编号模板","autoGenerateCode":true,"spec":{"uHeight":42,"widthMm":600,"depthMm":1200,"heightMm":2000}}`), &input); err != nil {
		t.Fatalf("unmarshal request: %v", err)
	}
	if !input.AutoGenerateCode || input.Code != "" || input.Name != "自动编号模板" {
		t.Fatalf("template create options were lost: %+v", input)
	}
	if input.Spec.UHeight != 42 || input.Spec.WidthMm != 600 || input.Spec.DepthMm != 1200 || input.Spec.HeightMm != 2000 {
		t.Fatalf("template dimensions were not decoded: %+v", input.Spec)
	}
}
