export interface AutoCodeCreateOption {
  autoGenerateCode?: boolean
}

export function withAutoGeneratedCode<T extends { code: string }>(payload: T, enabled: boolean): T & AutoCodeCreateOption {
  return {
    ...payload,
    code: enabled ? '' : payload.code,
    autoGenerateCode: enabled,
  }
}

export function hasRequiredCodeAndName(code: string, name: string, autoGenerateCode = false) {
  return Boolean(name.trim()) && (autoGenerateCode || Boolean(code.trim()))
}

/**
 * Batch import keeps a manually supplied code, but allows the cell to be blank.
 * The API receives the explicit autoGenerateCode flag so the server generates the
 * identifier at commit time and concurrent rows cannot reuse a client-side value.
 */
export function withOptionalImportCode<T extends { code: string }>(payload: T): T & AutoCodeCreateOption {
  const code = payload.code.trim()
  return {
    ...payload,
    code,
    autoGenerateCode: !code,
  }
}
