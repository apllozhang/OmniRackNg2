import { describe, expect, it } from 'vitest'
import { hasRequiredCodeAndName, withAutoGeneratedCode } from './autoCode'

describe('auto code create helpers', () => {
  it('clears a manually entered code when automatic generation is selected', () => {
    expect(withAutoGeneratedCode({ code: 'MANUAL-01', name: '测试资源' }, true)).toEqual({
      code: '', name: '测试资源', autoGenerateCode: true,
    })
  })

  it('preserves the code when automatic generation is disabled', () => {
    expect(withAutoGeneratedCode({ code: 'MANUAL-01', name: '测试资源' }, false)).toEqual({
      code: 'MANUAL-01', name: '测试资源', autoGenerateCode: false,
    })
  })

  it('requires code only in manual mode while always requiring name', () => {
    expect(hasRequiredCodeAndName('', '资源', true)).toBe(true)
    expect(hasRequiredCodeAndName('', '资源', false)).toBe(false)
    expect(hasRequiredCodeAndName('R-01', '', true)).toBe(false)
  })
})
